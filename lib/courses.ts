// 러닝 추천 경로 — 정적 큐레이션 목록. 지도(/map)에서 라인 레이어로 표시.
// 백엔드 0: 여기 배열만 고치면 됨. 크루장이 직접 큐레이션하는 방식.
//
// 좌표는 GeoJSON 표준 [경도(lng), 위도(lat)] 순서의 LineString.
// 채우는 법(둘 중 편한 걸로):
//  1) https://geojson.io 에서 코스를 LineString 으로 그린 뒤 coordinates 배열 복사 → 그대로 [lng,lat].
//  2) 직접 뛴 활동에서 추출: lib/icu.ts 의 getRouteCoords(activityId) 가 [lng,lat][] 를 돌려줌
//     (브라우저 콘솔에서 한 번 호출해 결과를 복붙).
//
// color 는 어두운 지도(dark-v11) 위에서 잘 보이는 밝은 색 권장.

export interface Course {
  id: string;
  /** 코스 이름 */
  name: string;
  /** 거리(km) */
  distance: number;
  /** 한 줄 설명(노면·특징 등) */
  desc?: string;
  /** 라인 색 (hex) */
  color: string;
  /** [lng, lat] 좌표 배열 (GeoJSON LineString 순서) */
  coords: [number, number][];
}

/** id 중복 시 뒤에 -2, -3… 붙여 고유하게. (강조/범례가 id 로 코스를 구분하므로 필수) */
export function withUniqueIds(courses: Course[]): Course[] {
  const seen = new Map<string, number>();
  return courses.map((c) => {
    const n = (seen.get(c.id) ?? 0) + 1;
    seen.set(c.id, n);
    return n === 1 ? c : { ...c, id: `${c.id}-${n}` };
  });
}

